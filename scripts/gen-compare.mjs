// Generates the comparison section of README.md from benchmarks/compare/results.json (measured) and docs/compare.json (manual
// cells and wording).
//   node scripts/gen-compare.mjs [README.md]          rewrite the section between the compare markers
//   node scripts/gen-compare.mjs [README.md] --check  fail if the data is invalid or the README section differs from the data
//   node scripts/gen-compare.mjs [README.md] --print  print the section (with markers) instead of writing it
// Options: --results=PATH, --data=PATH, --probes=PATH (defaults: benchmarks/compare/results.json, docs/compare.json,
// benchmarks/compare/probes.json).
// --check is offline and never fails because the data is old: nothing here reads the clock, and age is measured from the
// checkedOn date in the results. It passes with a message while the README has no compare markers or there is no results file.
// Text comes from fixed wording plus validated values (booleans, integers, versions, dates, enums, short plain-text notes), so a
// detail string from a probe never reaches the README.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const START =
  '<!-- compare:start (generated by scripts/gen-compare.mjs from benchmarks/compare/results.json and docs/compare.json, do not edit) -->';
export const END = '<!-- compare:end -->';
const START_PREFIX = '<!-- compare:start';

const MARK = { pass: '✅', partial: '⚠️', fail: '❌' };
const RESULTS = ['pass', 'partial', 'fail', 'error'];
// Reasons are chosen by the probe result only, never from detail strings.
const REASON = {
  'p1-raw-html': {
    pass: 'raw HTML shown as text',
    partial: 'some raw HTML kept as elements',
    fail: 'script runs',
    error: 'probe did not run',
  },
  'p2-link-schemes': {
    pass: 'unsafe link schemes blocked',
    partial: 'some unsafe link schemes kept',
    fail: 'unsafe link scheme kept',
    error: 'probe did not run',
  },
  'p3-remote-html': {
    pass: 'remote HTML not loaded',
    partial: 'some remote HTML loads',
    fail: 'remote HTML loads',
    error: 'probe did not run',
  },
  'p4-remote-md-image': {
    pass: 'markdown image not loaded',
    partial: 'markdown image loads in some cases',
    fail: 'markdown image loads without a click',
    error: 'probe did not run',
  },
};
const PROBES = ['p1-raw-html', 'p2-link-schemes', 'p3-remote-html', 'p4-remote-md-image', 'p5-link-target', 'p6-markers', 'p7-commonmark'];
const ROWS = ['framework', 'deps', 'safe', 'markers', 'commonmark', 'size', 'release'];
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// An em dash or an en dash, built from char codes so this file does not contain them.
const DASH = new RegExp(`[${String.fromCharCode(0x2013)}${String.fromCharCode(0x2014)}]`);
const PLACEHOLDER_WORD = /\b(TODO|TBD|FIXME|UNVERIFIED|XXX|PLACEHOLDER)\b/i;
const PLACEHOLDER_CELL = new Set(['?', '-', '--', '...', 'n/a']);
const SAFE_TEXT = /^[A-Za-z0-9 ,.:()+/`'_-]+$/;
// Printable ASCII only. Free text from results.json is escaped by esc() before it reaches the README.
// Probes that measure something no outside source defines. The footnote says that limmat's author wrote the probes.
const OWN_METHOD = new Set(['p6-markers']);
const FREE_TEXT = /^[\x20-\x7E]+$/;
const SEMVER = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
const ENV_VERSION = /^v?\d+(\.\d+){1,3}$/;
const URL_OK = /^https:\/\/[A-Za-z0-9./#_=&%-]+$/;
const ID = /^[a-z][a-z0-9-]*$/;

const isInt = (n) => Number.isInteger(n) && n >= 0;
const isDate = (s) => {
  if (typeof s !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const [y, m, d] = s.split('-').map(Number);
  const t = new Date(Date.UTC(y, m - 1, d));
  return t.getUTCFullYear() === y && t.getUTCMonth() === m - 1 && t.getUTCDate() === d;
};
const isText = (s, max) => typeof s === 'string' && s.length > 0 && s.length <= max && SAFE_TEXT.test(s);
const isFree = (s, max) => typeof s === 'string' && s.length > 0 && s.length <= max && FREE_TEXT.test(s);
// Backslash-escape every character that markdown or a table cell could read as syntax, except inside `code spans`, which are literal.
const esc = (s) =>
  s
    .split(/(`[^`\n]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/[\\`*_{}[\]<>|&#~!]/g, '\\$&')))
    .join('');
const toUtc = (iso) => {
  const [y, m, d] = iso.split('-').map(Number);
  return Date.UTC(y, m - 1, d);
};

// Everything that makes the data unusable. Age is never a problem: no clock is read.
export function validate(results, data, probes) {
  const p = [];
  const bad = (msg) => p.push(msg);

  // docs/compare.json
  if (data?.schema !== 1) bad('compare.json: schema must be 1');
  else {
    if (!Array.isArray(data.order) || !data.order.length || !data.order.every((id) => typeof id === 'string' && ID.test(id)))
      bad('compare.json: order must be a list of tool ids');
    for (const [id, t] of Object.entries(data.tools ?? {})) {
      if (!ID.test(id)) bad(`compare.json: bad tool id "${id}"`);
      if (!isText(t?.name, 40)) bad(`compare.json: tools.${id}.name must be short plain text`);
      if (typeof t?.docs !== 'string' || !URL_OK.test(t.docs)) bad(`compare.json: tools.${id}.docs must be an https URL`);
    }
    for (const id of data.order ?? []) if (!data.tools?.[id]) bad(`compare.json: order names "${id}", which has no entry in tools`);
    for (const k of ['corner', ...ROWS]) if (!isText(data.rows?.[k], 60)) bad(`compare.json: rows.${k} must be short plain text`);
    for (const [id, notes] of Object.entries(data.cellNotes ?? {})) {
      if (!data.tools?.[id]) bad(`compare.json: cellNotes.${id} is not a tool`);
      for (const [row, note] of Object.entries(notes)) {
        if (!ROWS.includes(row)) bad(`compare.json: cellNotes.${id}.${row} is not a row`);
        if (!isText(note, 80)) bad(`compare.json: cellNotes.${id}.${row} must be short plain text`);
      }
    }
    for (const k of ['frameworkNames', 'outputNames'])
      for (const [key, name] of Object.entries(data[k] ?? {}))
        if (!isText(name, 40)) bad(`compare.json: ${k}.${key} must be short plain text`);
    if (data.lead !== undefined && (typeof data.lead !== 'string' || !data.lead.trim()))
      bad('compare.json: lead must be a non-empty string');
    const f = data.footer;
    for (const k of ['intro', 'detailsSummary', 'versions'])
      if (typeof f?.[k] !== 'string' || !f[k].trim()) bad(`compare.json: footer.${k} is empty`);
    if (!Array.isArray(f?.metrics) || !f.metrics.length || f.metrics.some((m) => typeof m !== 'string' || !m.trim()))
      bad('compare.json: footer.metrics must be a list of non-empty strings');
  }

  // results.json
  const r = results;
  if (r?.schema !== 1) {
    bad('results.json: schema must be 1');
    return p;
  }
  if (!isDate(r.checkedOn)) bad('results.json: checkedOn must be YYYY-MM-DD');
  for (const k of ['node', 'playwright', 'chromium'])
    if (typeof r.environment?.[k] !== 'string' || !ENV_VERSION.test(r.environment[k]))
      bad(`results.json: environment.${k} must be a version`);
  if (!Array.isArray(r.tools) || !r.tools.length) {
    bad('results.json: tools must be a non-empty list');
    return p;
  }
  const seen = new Set();
  for (const t of r.tools) {
    const id = t?.id;
    if (typeof id !== 'string' || !ID.test(id)) {
      bad('results.json: a tool has no valid id');
      continue;
    }
    const at = `results.json: ${id}`;
    if (seen.has(id)) bad(`${at}: listed twice`);
    seen.add(id);
    if (data?.tools && !data.tools[id]) bad(`${at}: not in docs/compare.json (add its name, docs link, and notes there)`);
    if (data?.order && !data.order.includes(id)) bad(`${at}: not in compare.json order`);
    if (typeof t.version !== 'string' || !SEMVER.test(t.version)) bad(`${at}: version must be semver`);
    if (!isText(t.versionLabel, 30)) bad(`${at}: versionLabel must be short plain text`);
    if (typeof t.npm !== 'string' || !/^[a-z0-9@/._-]{1,80}$/.test(t.npm)) bad(`${at}: npm must be a package name`);
    if (typeof t.repo !== 'string' || !/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(t.repo)) bad(`${at}: repo must be owner/name`);
    for (const k of ['releaseDate', 'firstRelease', 'lastCommit']) if (!isDate(t[k])) bad(`${at}: ${k} must be YYYY-MM-DD`);
    if (typeof t.framework !== 'string' || !ID.test(t.framework)) bad(`${at}: framework must be none or a framework id`);
    else if (t.framework !== 'none' && data?.frameworkNames && !data.frameworkNames[t.framework])
      bad(`${at}: framework "${t.framework}" has no name in compare.json frameworkNames`);
    if (!['dom', 'react', 'html-string'].includes(t.output)) bad(`${at}: output must be dom, react, or html-string`);
    else if (data?.outputNames && !data.outputNames[t.output]) bad(`${at}: output "${t.output}" has no name in compare.json outputNames`);
    for (const k of ['directDeps', 'totalDeps', 'gzipBytes']) if (!isInt(t[k])) bad(`${at}: ${k} must be a non-negative integer`);
    if (isInt(t.directDeps) && isInt(t.totalDeps) && t.directDeps > t.totalDeps) bad(`${at}: directDeps is more than totalDeps`);
    if (isInt(t.gzipBytes) && t.gzipBytes === 0) bad(`${at}: gzipBytes is 0`);
    if (!isFree(t.gzipNote, 160)) bad(`${at}: gzipNote must be short printable ASCII text`);
    if (!isFree(t.defaultConfig, 300)) bad(`${at}: defaultConfig must be one printable ASCII sentence`);
    for (const key of PROBES) {
      const pr = t.probes?.[key];
      if (!pr || typeof pr !== 'object') {
        bad(`${at}: probe ${key} is missing`);
        continue;
      }
      if (key === 'p7-commonmark') {
        if (pr.result !== 'info') bad(`${at}: ${key}.result must be info`);
        for (const k of ['passed', 'total', 'strict', 'textOnly'])
          if (!isInt(pr[k])) bad(`${at}: ${key}.${k} must be a non-negative integer`);
        if (isInt(pr.total) && pr.total === 0) bad(`${at}: ${key}.total is 0`);
        if (isInt(pr.passed) && isInt(pr.total) && pr.passed > pr.total) bad(`${at}: ${key}.passed is more than total`);
      } else {
        if (!RESULTS.includes(pr.result)) bad(`${at}: ${key}.result must be pass, partial, fail, or error`);
        if (key === 'p6-markers') {
          for (const k of ['leaked', 'constructs']) if (!isInt(pr[k])) bad(`${at}: ${key}.${k} must be a non-negative integer`);
          if (isInt(pr.constructs) && pr.constructs === 0) bad(`${at}: ${key}.constructs is 0`);
          if (isInt(pr.leaked) && isInt(pr.constructs) && pr.leaked > pr.constructs) bad(`${at}: ${key}.leaked is more than constructs`);
          if (isInt(pr.leaked) && pr.result !== 'error' && pr.leaked > 0 !== (pr.result !== 'pass'))
            bad(`${at}: ${key}.result ${pr.result} does not match leaked ${pr.leaked}`);
        }
      }
    }
  }
  if (!seen.has('limmat')) bad('results.json: limmat is missing');

  // benchmarks/compare/probes.json: every probe needs a source URL. Its shape is a list of probes, an object with a "probes"
  // list or map, or a map keyed by probe id.
  if (probes !== undefined) {
    const list = Array.isArray(probes)
      ? probes
      : Array.isArray(probes?.probes)
        ? probes.probes
        : Object.values(probes?.probes && typeof probes.probes === 'object' ? probes.probes : (probes ?? {}));
    const entries = list.filter((e) => e && typeof e === 'object');
    if (!entries.length) bad('probes.json: no probes found');
    for (const [i, e] of entries.entries()) {
      const urls = Array.isArray(e.sources) ? e.sources : [e.source ?? e.sourceUrl ?? e.url];
      if (OWN_METHOD.has(e.id) && !urls.filter(Boolean).length) continue;
      if (!urls.length || !urls.every((u) => typeof u === 'string' && /^https:\/\//.test(u)))
        bad(`probes.json: probe ${e.id ?? i} has no https source URL`);
    }
  }
  return p;
}

const pct = (r) => (r.passed / r.total) * 100;

function fill(text, vars) {
  return text.replace(/\{(\w+)\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`unknown placeholder {${k}}`);
    return String(vars[k]);
  });
}

function bucket(releaseDate, checkedOn) {
  const [y, m, d] = releaseDate.split('-').map(Number);
  const now = toUtc(checkedOn);
  if (now < Date.UTC(y, m - 1 + 3, d)) return 'under 3 months';
  if (now < Date.UTC(y + 1, m - 1, d)) return 'under 1 year';
  return 'over 1 year';
}

const kb = (bytes) => (bytes / 1000).toFixed(1);

function combine(results) {
  if (results.includes('fail')) return 'fail';
  if (results.includes('error') || results.includes('partial')) return 'partial';
  return 'pass';
}

// The reasons for a combined mark: all phrases when everything passes, otherwise only the ones that are not a pass.
function reasons(keys, t) {
  const rs = keys.map((k) => [k, t.probes[k].result]);
  const shown = rs.every(([, r]) => r === 'pass') ? rs : rs.filter(([, r]) => r !== 'pass');
  return shown.map(([k, r]) => REASON[k][r]).join(', ');
}

function cells(t, data, checkedOn) {
  const pr = t.probes;
  const c = {};
  c.framework = t.framework === 'none' ? MARK.pass : `${MARK.fail} ${data.frameworkNames[t.framework]}`;
  c.deps = `${t.totalDeps === 0 ? MARK.pass : t.totalDeps <= 5 ? MARK.partial : MARK.fail} ${t.totalDeps}`;
  c.safe = MARK[combine([pr['p1-raw-html'].result, pr['p2-link-schemes'].result])];
  c.markers = MARK[combine([pr['p6-markers'].result])];
  const share = pct(pr['p7-commonmark']);
  c.commonmark = `${share > 80 ? MARK.pass : share >= 50 ? MARK.partial : MARK.fail} ${Math.round(share)}%`;
  c.size = `${kb(t.gzipBytes)} kB`;
  const [y, m] = t.releaseDate.split('-').map(Number);
  const month = `${MONTHS[m - 1]}&nbsp;${y}`;
  c.release = bucket(t.releaseDate, checkedOn) === 'over 1 year' ? `**${month}**` : month;
  return c;
}

const andList = (items) => (items.length <= 2 ? items.join(' and ') : `${items.slice(0, -1).join(', ')}, and ${items.at(-1)}`);
const names = (list, data) => andList(list.map((t) => data.tools[t.id].name));

// Plain-language details for the table rows, derived from the probe results.
function details(tools, data) {
  const out = [];
  const notSafe = tools.filter((t) => combine([t.probes['p1-raw-html'].result, t.probes['p2-link-schemes'].result]) !== 'pass');
  if (notSafe.length)
    out.push(
      `Safe by default: ${notSafe.map((t) => `${data.tools[t.id].name}: ${reasons(['p1-raw-html', 'p2-link-schemes'], t)}`).join('; ')}.`,
    );
  const leaky = tools.filter((t) => t.probes['p6-markers'].leaked > 0);
  const own = leaky.map((t) => data.details?.markersNotes?.[t.id]).filter(Boolean);
  const markersNote = [data.details?.markersNote, ...own]
    .filter(Boolean)
    .map((n) => ` ${n}`)
    .join('');
  if (leaky.length)
    out.push(
      `Raw markers while streaming: ${andList(leaky.map((t) => `${data.tools[t.id].name} ${t.probes['p6-markers'].leaked} of ${t.probes['p6-markers'].constructs} constructs`))}.${markersNote}`,
    );
  const imgFail = tools.filter((t) => t.probes['p4-remote-md-image'].result === 'fail');
  const htmlFail = tools.filter((t) => t.probes['p3-remote-html'].result === 'fail');
  const parts = [];
  if (imgFail.length)
    parts.push(
      imgFail.length === tools.length
        ? 'Every library loads a remote markdown image without a click.'
        : `Remote markdown images load without a click in ${names(imgFail, data)}.`,
    );
  if (htmlFail.length) parts.push(`Raw HTML images also load in ${names(htmlFail, data)}.`);
  if (imgFail.some((t) => t.id === 'limmat') && data.details?.limmatImages) parts.push(data.details.limmatImages);
  if (parts.length) out.push(`Remote loads: ${parts.join(' ')}`);
  return out;
}

// The section between the markers, markers included. Throws on data that validate() would reject, so call that first.
export function render(results, data) {
  const tools = data.order.map((id) => results.tools.find((t) => t.id === id)).filter(Boolean);
  const by = Object.fromEntries(tools.map((t) => [t.id, t]));
  const cols = tools.map((t) => cells(t, data, results.checkedOn));
  const head = tools.map((t) => `[${data.tools[t.id].name}](${data.tools[t.id].docs})`);
  const out = [
    START,
    ...(data.lead ? [data.lead, ''] : []),
    `| ${data.rows.corner} | ${head.join(' | ')} |`,
    `|---|${tools.map(() => '---').join('|')}|`,
  ];
  for (const row of ROWS) out.push(`| ${data.rows[row]} | ${cols.map((c) => c[row]).join(' | ')} |`);

  const cm = by.limmat.probes['p7-commonmark'];
  const vars = {
    checkedOn: results.checkedOn,
    versions: tools.map((t) => `${data.tools[t.id].name} ${t.version}`).join(', '),
    node: results.environment.node.replace(/^v/, ''),
    playwright: results.environment.playwright,
    chromium: results.environment.chromium,
    cmTotal: cm.total,
  };
  const f = data.footer;
  const notes = details(tools, data);
  out.push('', fill(f.intro, vars), '');
  out.push('<details>', `<summary>${f.detailsSummary}</summary>`, '');
  for (const n of notes) out.push(`- ${n}`);
  for (const m of f.metrics) out.push(`- ${fill(m, vars)}`);
  out.push('', fill(f.versions, vars), '');
  for (const t of tools)
    out.push(
      `- ${data.tools[t.id].name} ${t.versionLabel}: ${esc(t.defaultConfig)} Size: ${esc(t.gzipNote)}. ([docs](${data.tools[t.id].docs}))`,
    );
  out.push('', '</details>');
  out.push(END);
  return out.join('\n');
}

// Problems in the rendered text: dashes, placeholders, and empty table cells.
export function lint(text) {
  const p = [];
  text.split('\n').forEach((line, i) => {
    if (DASH.test(line)) p.push(`output line ${i + 1}: em or en dash`);
    if (PLACEHOLDER_WORD.test(line)) p.push(`output line ${i + 1}: placeholder word`);
    if (/^\|/.test(line)) {
      for (const cell of line.split('|').slice(1, -1)) {
        const s = cell.trim().toLowerCase();
        if (!s || PLACEHOLDER_CELL.has(s)) p.push(`output line ${i + 1}: empty or placeholder cell "${cell.trim()}"`);
      }
    } else if (/(^|\s)\?(\s|$)/.test(line)) p.push(`output line ${i + 1}: a lone question mark`);
  });
  return p;
}

// Finds the generated section in a README: null if it has no markers, or throws if they are broken.
export function locate(readme) {
  const a = readme.indexOf(START_PREFIX);
  const b = readme.indexOf(END);
  if (a < 0 && b < 0) return null;
  if (a < 0 || b < 0 || b < a) throw new Error('README has a compare marker without its partner, or the end marker comes first');
  return [a, b + END.length];
}

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

function main(argv) {
  const opt = (name, dflt) => argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? dflt;
  const readmePath = argv.find((a) => !a.startsWith('--')) ?? 'README.md';
  const resultsPath = opt('results', 'benchmarks/compare/results.json');
  const dataPath = opt('data', 'docs/compare.json');
  const probesPath = opt('probes', 'benchmarks/compare/probes.json');
  const check = argv.includes('--check');

  const readme = readFileSync(readmePath, 'utf8');
  let span;
  try {
    span = locate(readme);
  } catch (e) {
    console.error(`${readmePath}: ${e.message}`);
    return 1;
  }
  const hasResults = existsSync(resultsPath);
  if (!hasResults && !(check && !span)) {
    console.error(`${resultsPath} does not exist`);
    return 1;
  }

  let data;
  let results;
  let probes;
  try {
    data = readJson(dataPath);
    if (hasResults) results = readJson(resultsPath);
    if (existsSync(probesPath)) probes = readJson(probesPath);
  } catch (e) {
    console.error(`could not read the compare data: ${e.message}`);
    return 1;
  }
  if (!results) {
    // Check mode, no markers yet, and no results yet: only the manual file is checked.
    const problems = validate({ schema: 0 }, data, probes).filter((m) => m.startsWith('compare.json') || m.startsWith('probes.json'));
    if (problems.length) {
      console.error(problems.join('\n'));
      return 1;
    }
    console.log('compare table: no results.json and no compare markers in the README yet, only docs/compare.json was checked');
    return 0;
  }

  const problems = validate(results, data, probes);
  let section = '';
  if (!problems.length) {
    try {
      section = render(results, data);
    } catch (e) {
      problems.push(`render failed: ${e.message}`);
    }
    if (section) problems.push(...lint(section));
  }
  if (problems.length) {
    console.error(problems.join('\n'));
    return 1;
  }

  if (argv.includes('--print')) {
    console.log(section);
    return 0;
  }
  if (!span) {
    if (check) {
      console.log('compare table: data ok, README has no compare markers yet, so the table was not compared');
      return 0;
    }
    console.error(`${readmePath} has no compare:start and compare:end markers: run with --print and paste the section where it belongs`);
    return 1;
  }
  const next = readme.slice(0, span[0]) + section + readme.slice(span[1]);
  if (check) {
    if (next !== readme) {
      console.error('README compare table is out of date: run `npm run compare:table`');
      return 1;
    }
  } else writeFileSync(readmePath, next);
  console.log(`compare table: ${results.tools.length} libraries ok`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(main(process.argv.slice(2)));
