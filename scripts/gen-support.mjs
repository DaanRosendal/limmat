// Generates the support table in README.md from docs/support.json. The table is short on purpose: feature, status, note, with
// related rows merged (see "readmeRow" below). The CommonMark counts and the cited tests are checked here and shown in the demo,
// but not printed in the README.
//   node scripts/gen-support.mjs          rewrite the table
//   node scripts/gen-support.mjs --check  fail if README.md is out of date or the data is dishonest
// Checked on every run: statuses are known, cited test files exist and contain the quoted title, CommonMark sections
// exist, and a row can only say "supported" if at least 80% of its CommonMark examples pass.
import { readFileSync, writeFileSync } from 'node:fs';
import { LABEL, rows, sections, specCounts } from './support-data.mjs';

const START = '<!-- support:start (generated by scripts/gen-support.mjs from docs/support.json, do not edit) -->';
const END = '<!-- support:end -->';
// Colour dots show in GitHub's Markdown, which allows no CSS. The word stays, so colour is never the only signal.
const DOT = { supported: '✅', partial: '⚠️', 'not-yet': '❌', wont: '❌' };
const problems = [];

for (const r of rows) {
  if (!LABEL[r.status]) problems.push(`${r.feature}: unknown status "${r.status}"`);
  let cm = '';
  const spec = specCounts(r);
  if (spec) {
    for (const name of r.cm) if (!sections[name]) problems.push(`${r.feature}: no CommonMark section "${name}"`);
    cm = `${spec.pass}/${spec.total}`;
    if (r.status === 'supported' && spec.total && spec.pass / spec.total < 0.8)
      problems.push(`${r.feature}: marked supported but only ${cm} spec examples pass`);
  }
  const proof = (r.tests ?? []).map((t) => {
    let src = '';
    try {
      src = readFileSync(t.file, 'utf8');
    } catch {
      problems.push(`${r.feature}: test file ${t.file} does not exist`);
    }
    if (src && !src.includes(t.title)) problems.push(`${r.feature}: "${t.title}" not found in ${t.file}`);
    return t.title;
  });
  if (!cm && !proof.length && r.status !== 'not-yet') problems.push(`${r.feature}: a ${r.status} row needs a CommonMark section or a test`);
}

// Rows that share a "readmeRow" label become one README row. They must share a status, so a green row cannot hide a gap. The
// note is the group's "readmeNote" (on one row at most), or else the rows' own notes joined. A row with "readme": false is left out.
const groups = [];
const byLabel = new Map();
for (const r of rows) {
  if (r.readme === false) continue;
  const label = r.readmeRow ?? r.feature;
  let g = byLabel.get(label);
  if (!g) {
    g = { label, status: r.status, rows: [] };
    byLabel.set(label, g);
    groups.push(g);
  } else if (g.status !== r.status) problems.push(`${r.feature}: readmeRow "${label}" mixes statuses (${g.status} and ${r.status})`);
  g.rows.push(r);
}
const lines = groups.map((g) => {
  const notes = g.rows.filter((r) => r.readmeNote !== undefined);
  if (notes.length > 1) problems.push(`readmeRow "${g.label}" has more than one readmeNote`);
  const note = notes.length
    ? notes[0].readmeNote
    : g.rows
        .map((r) => r.note)
        .filter(Boolean)
        .join(' ');
  return `| ${g.label} | ${`${DOT[g.status]} ${LABEL[g.status]}`.replace(/ /g, '&nbsp;')} | ${note} |`;
});
const table = [START, '| Feature | Status | Note |', '|---|---|---|', ...lines, END].join('\n');
const readme = readFileSync('README.md', 'utf8');
const a = readme.indexOf('<!-- support:start');
const b = readme.indexOf(END);
if (a < 0 || b < 0) problems.push('README.md has no support:start and support:end markers');
const next = problems.length ? readme : readme.slice(0, a) + table + readme.slice(b + END.length);

if (process.argv.includes('--check')) {
  if (next !== readme) problems.push('README.md support table is out of date: run `npm run support`');
} else if (!problems.length) writeFileSync('README.md', next);

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
console.log(`support section: ${rows.length} rows ok`);
